        # Side chain RMSD
        # Calculate average side chain RMSD for all successful entries
        avg_sidechain_rmsd = success_df['fixedpos_sidechain_rmsd'].astype(float).mean() if 'fixedpos_sidechain_rmsd' in success_df.columns else float('nan')
